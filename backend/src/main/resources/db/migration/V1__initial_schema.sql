CREATE TABLE categories (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(60) NOT NULL UNIQUE);
CREATE TABLE tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(120) NOT NULL, description VARCHAR(2000) NOT NULL,
 status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING','IN_PROGRESS','COMPLETED')),
 category_id BIGINT NOT NULL REFERENCES categories(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, due_date DATE
);
CREATE INDEX idx_tasks_created ON tasks(created_at, id);
CREATE INDEX idx_tasks_category ON tasks(category_id);
